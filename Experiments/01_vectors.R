# EXPERIMENT 1: Numeric, Character, and Logical Vectors
# INPUTS (already included below):
# Numeric values: 10, 20, 30, 40, 50
# Character values: Apple, Banana, Mango
# Logical values: TRUE, FALSE, TRUE, TRUE

numeric_vector <- c(10, 20, 30, 40, 50)
character_vector <- c("Apple", "Banana", "Mango")
logical_vector <- c(TRUE, FALSE, TRUE, TRUE)

cat("Numeric vector:\n"); print(numeric_vector)
cat("Character vector:\n"); print(character_vector)
cat("Logical vector:\n"); print(logical_vector)

cat("Data types:\n")
print(typeof(numeric_vector))
print(typeof(character_vector))
print(typeof(logical_vector))
